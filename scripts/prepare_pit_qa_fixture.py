#!/usr/bin/env python3
"""Build a deterministic PIT fixture inside an isolated QA root.

The generated bytes are synthetic test evidence and are deliberately marked
``production_eligible=false``.  They exercise the real immutable membership,
dual-price ledger, runtime binding, cache, benchmark and database code paths;
they are never copied into the repository's production ``data/`` directory.
"""

